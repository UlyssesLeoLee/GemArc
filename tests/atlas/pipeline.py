"""Scripted pipelines of milestone M8: the REAL tool functions driven end to end by a script (no model in the loop).

``Session`` calls the registered tool functions of ``gemarc_mcp.atlas_tools`` inside the product gates, exactly as the MCP binding
does (``atlas_tools._bind``), and writes down for every call the bytes of the request (what an AI writes: the arguments as compact
JSON) and of the reply (what it reads: the compact JSON text the server sends, after the 20 KiB safety net), the wall time and the
phase. ``tests/atlas/test_pipeline_m8.py`` asserts on those records, ``tools/pilot/ledger.py`` aggregates them into the token
ledger. Everything here is synthetic: models come from ``synth.py``, source trees, requirement texts and user answers are
generated by the functions below.

Three drivers:

* ``run_fixture(preset, seed, ...)``: a generated model (tiny, small, reference) is put slice by slice and taken to ``done``.
  The generator does not produce a finished atlas on purpose (Entity and Table nodes lack ``columns``, TBDs are open, ``user:``
  evidence has no saved text), so the script plays the people around the AI: it adds the columns, writes the user's answers to
  ``atlas/user/`` and states each decision as a ``by=user`` policy quoting them;
* ``run_greenfield(...)``: a requirement brief is saved, then requirements, tests, TBDs, policies, space, nodes with ``user:``
  evidence, edges, cases and expectations follow in the elicitation order of design 8.3 (to-be);
* ``run_asis(...)``: a repository of about 25 modules is generated, the script reads each module through the ``outline`` tool,
  takes the anchors from it and authors nodes, edges, evidence, cases and expectations (as-is).

Expectations written from engine output (``consistent``) are a test FIXTURE here, made before the project exists; the oracle rules
(``test_oracle_cheaters.py``) are about an AI that sees a result before it writes. The greenfield and as-is drivers write the
expectations from the requirements and the call graph instead.
"""
