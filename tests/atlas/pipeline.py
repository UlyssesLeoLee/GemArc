DECISION_SENTENCE = "keep the current behaviour for this item and review it next quarter"
SENSITIVE = ("user:",)


def fixture_model(preset: str, seed: int) -> dict:
    """A generated model whose expectations are engine-consistent (a fixture) and whose Entity and Table nodes have columns."""
    model = consistent(synth.generate(preset, seed))
    for node in model["nodes"]:
        if node["kind"] in ("Entity", "Table") and not (node.get("props") or {}).get("columns"):
            node.setdefault("props", {})["columns"] = [{"name": "id", "pk": True}, "status", "label"]
    return model


def evidence_files(model: dict) -> dict:
    """``{(alias, relative path): [anchor, ...]}`` of the rows that name a file in a repository (``user:`` rows are texts, not files)."""
    files: dict = {}
    for row in model["evidences"]:
        if str(row["filePath"]).startswith("user:"):
            continue
        files.setdefault((row["repository"], row["filePath"]), []).append(row["anchor"])
    return files


def write_evidence_root(model: dict, base: Path) -> dict:
    """Generate a synthetic source tree that holds every cited anchor on a line of its own; returns ``{alias: directory}``.

    Each anchor sits once in its file (the test asserts it): the real verifier would report an ambiguous anchor otherwise."""
    roots: dict = {}
    for (alias, rel), anchors in sorted(evidence_files(model).items()):
        root = base / (alias or "main")
        roots[alias or "main"] = root
        target = root / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        lines = []
        for index, anchor in enumerate(anchors):
            lines += [f"# section {index}", anchor, "    pass", ""]
        target.write_bytes(("\n".join(lines)).encode("utf-8"))
    return roots


def user_texts_of(model: dict) -> dict:
    """``{name: text}`` for the ``user:<name>`` evidence rows: the saved text holds each quoted anchor sentence verbatim."""
    out: dict = {}
    for row in model["evidences"]:
        path = str(row["filePath"])
        if path.startswith("user:"):
            out.setdefault(path[5:], []).append(row["anchor"])
    return {name: "\n".join(anchors) + "\n" for name, anchors in out.items()}


def decisions_slice(model: dict) -> "tuple[str, str]":
    """The policies the user's answers become: one ``by=user`` row per open TBD, quoting ``DECISION_SENTENCE``; plus a non-functional
    row (chapter 9 of the requirement document is NOT-AUTHORED without a non-functional policy). Returns ``(answers text, slice text)``."""
    answers, rows = [], []
    for number, tbd in enumerate(model.get("tbds", ()), start=1):
        answers.append(f"Decision for {tbd['id']}: {DECISION_SENTENCE}.")
        rows.append(f"PL-DEC-{number} | The user decided to '{DECISION_SENTENCE}'. | src={tbd['id']} by=user kind=constraint")
    rows.append(f"PL-NFR-M8 | The service answers within a bounded time. | src={model['requirements'][0]['id']} kind=nfr")
    text = "#atlas 1\n## policies: id | text | opts\n" + "\n".join(rows) + "\n" if rows else ""
    return ("\n".join(answers) + "\n" if answers else ""), text


def stage_slices(model: dict) -> dict:
    return slice_texts(model)


def run_fixture(preset: str, seed: int, workspace: Path, scratch: Path, *, gate: str = "none", project: str = PROJECT, verify_widths=None, browser: bool = True) -> dict:
    """One scripted fixture run: init, put every slice, resolve what only people can (answers, saved texts), simulate, evidence,
    build, doc, optional browser gate, review report and record, status. Returns ``{session, model, final, steps}``.

    ``scratch`` receives the synthetic evidence root. Nothing is written outside ``workspace`` and ``scratch``. ``browser=False`` skips the
    browser gate and waives it the way the user would (a test that needs only a finished project)."""
    model = fixture_model(preset, seed)
    roots = write_evidence_root(model, scratch / "roots")
    steps: dict = {}
    with Session(workspace, roots, project=project) as s:
        s.phase = "orient"
        s.call("brief", "orient", section="all", lang=LANG)
        created = s.call("init", "orient", title=f"Scripted {preset} atlas", mode="asis", languages=[LANG], repos=sorted(roots))
        steps["init"] = created
        for name, text in stage_slices(model).items():
            reply = s.put(name, text)
            if reply["status"] != "committed":
                raise AssertionError(f"put {name}: {json.dumps(reply)[:400]}")
        steps["after-puts"] = s.status("author")
        answers, decisions = decisions_slice(model)
        if answers:
            s.write_user_text("answers", answers)
        for name, text in user_texts_of(model).items():
            s.write_user_text(name, text)
        if decisions:
            reply = s.put("900-decisions", decisions)
            if reply["status"] != "committed":
                raise AssertionError(f"put decisions: {json.dumps(reply)[:400]}")
        steps["structure"] = s.status("author")
        steps["simulate"] = s.call("simulate", "gates")
        steps["evidence"] = s.call("evidence", "gates")
        steps["build"] = s.call("build", "gates", gate=gate)
        steps["doc"] = s.call("doc", "gates", unit="system", level="BD", lang=LANG)
        steps["browser"] = "BUILD-GATE" if gate == "smoke" else "NOT-RUN"
        if gate == "none" and not browser:      # a caller that does not need the page checked (the kit test): the user waives the gate in their own file
            s.waive_browser("the browser gate is not run in this scripted project")
            steps["browser"] = "WAIVED"
        elif gate == "none":
            steps["verify"] = s.call("verify", "gates", **({"widths": list(verify_widths)} if verify_widths else {}))
            steps["browser"] = steps["verify"].get("gate", "NOT-RUN")
            if steps["verify"].get("code") == "GEMARC_ATLAS_BUILD_031":      # no browser on this machine: only the user can waive the gate
                s.waive_browser("this machine has no browser; the user opens the page by hand")
                steps["browser"] = "WAIVED"
        steps["status-before-review"] = s.status("gates")
        steps["report"] = s.call("review", "review", action="report")
        steps["record"] = s.call("review", "review", action="record", notes="fixed=; open=")
        final = s.status("final")
    return {"session": s, "model": model, "final": final, "steps": steps, "roots": roots}
