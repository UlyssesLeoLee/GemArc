def compact(value) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def nbytes(value) -> int:
    return len(compact(value).encode("utf-8"))


class Session:
    """A workspace, an optional evidence-roots table and the recorded tool calls of one scripted run.

    Use as a context manager: it sets ``GEMARC_WORKSPACE_ROOT``, ``GEMARC_ALLOW_WRITE`` and ``GEMARC_ATLAS_ROOTS`` for the calls and
    restores the environment afterwards. ``call`` runs the registered function of the tool inside ``status.product_gates()`` and the
    server's ``fit_result`` safety net, so the reply is what a client receives.
    """

    def __init__(self, workspace: Path, roots: "dict | None" = None, *, project: str = PROJECT, write: bool = True):
        self.workspace = Path(workspace)
        self.roots = dict(roots or {})
        self.project = project
        self.write = write
        self.records: list = []
        self.phase = "orient"
        self._patch = None
        self._tools = {spec.name: atlas_tools._bind(spec.fn, safe_response) for spec in atlas_tools.tools_of(atlas_tools.LOCAL)}  # noqa: SLF001

    # -- environment -----------------------------------------------------------------------------------------------

    def __enter__(self) -> "Session":
        env = {"GEMARC_WORKSPACE_ROOT": str(self.workspace), "GEMARC_ALLOW_WRITE": "1" if self.write else "0", "PYTHONUTF8": "1"}
        env["GEMARC_ATLAS_ROOTS"] = ";".join(f"{alias}={path}" for alias, path in self.roots.items())
        self._patch = mock.patch.dict(os.environ, env)
        self._patch.start()
        if not self.roots:
            os.environ.pop("GEMARC_ATLAS_ROOTS", None)
        return self

    def __exit__(self, *exc) -> None:
        self._patch.stop()

    @property
    def project_dir(self) -> Path:
        return self.workspace / self.project

    @property
    def atlas_dir(self) -> Path:
        return self.project_dir / "atlas"

    @property
    def dist(self) -> Path:
        return self.atlas_dir / "dist"

    # -- calls -----------------------------------------------------------------------------------------------------

    def call(self, tool: str, phase: str = "", **arguments) -> dict:
        """One tool call. ``tool`` is the full name or the part after ``gemarc_atlas_``; the project is added when the tool takes one."""
        name = tool if tool.startswith("gemarc_atlas_") else f"gemarc_atlas_{tool}"
        spec = next(s for s in atlas_tools.tools_of(atlas_tools.LOCAL) if s.name == name)
        wants_project = "project" in spec.fn.__code__.co_varnames[: spec.fn.__code__.co_argcount]
        if wants_project and "project" not in arguments:
            arguments = {"project": self.project, **arguments}
        started = time.perf_counter()
        payload = self._tools[name](**arguments)
        seconds = time.perf_counter() - started
        if isinstance(payload, dict):
            payload = core.fit_result(payload, core.HARD_CAP)
        self.records.append({"tool": name, "phase": phase or self.phase, "request": nbytes(arguments), "reply": nbytes(payload),
                             "text": len(str(arguments.get("text", "")).encode("utf-8")), "seconds": round(seconds, 4),
                             "status": payload.get("status") if isinstance(payload, dict) else None})
        return payload

    def put(self, slice_name: str, text: str, phase: str = "author", **kw) -> dict:
        return self.call("put", phase, slice=slice_name, text=text, **kw)

    def status(self, phase: str = "author", **kw) -> dict:
        return self.call("status", phase, **kw)

    # -- files the people around the AI write ---------------------------------------------------------------------

    def write_user_text(self, name: str, text: str) -> Path:
        """``atlas/user/<name>.txt``: what the user said, saved verbatim by the AI's own file tool."""
        target = self.atlas_dir / "user" / f"{name}.txt"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(text.encode("utf-8"))
        return target

    def waive_browser(self, reason: str) -> Path:
        """``atlas/waive-browser.txt``: the user's own file (no tool writes it); a SKIPPED gate then stops blocking, a FAILED one never does."""
        target = self.atlas_dir / "waive-browser.txt"
        target.write_bytes((reason + "\n").encode("utf-8"))
        return target

    # -- reporting -------------------------------------------------------------------------------------------------

    def tool_sums(self) -> dict:
        """``{tool: {calls, request, reply, seconds}}`` over the records of this run."""
        out: dict = {}
        for r in self.records:
            row = out.setdefault(r["tool"], {"calls": 0, "request": 0, "reply": 0, "text": 0, "seconds": 0.0, "maxReply": 0})
            row["calls"] += 1
            row["request"] += r["request"]
            row["reply"] += r["reply"]
            row["text"] += r.get("text", 0)
            row["seconds"] = round(row["seconds"] + r["seconds"], 4)
            row["maxReply"] = max(row["maxReply"], r["reply"])
        return out

    def by_phase(self) -> dict:
        out: dict = {}
        for r in self.records:
            row = out.setdefault(r["phase"], {"calls": 0, "request": 0, "reply": 0, "text": 0})
            row["calls"] += 1
            row["request"] += r["request"]
            row["reply"] += r["reply"]
            row["text"] += r.get("text", 0)
        return out


@contextmanager
def session(workspace: Path, roots: "dict | None" = None, **kw):
    with Session(workspace, roots, **kw) as s:
        yield s


class StdioSession(Session):
    """The same driver interface over REAL MCP stdio: every ``call`` is a ``tools/call`` to a ``python -m gemarc_mcp`` child process (tool set
    ``atlas``, an explicit filtered environment as Claude Code, Codex and Hermes give it). The driver is synchronous and runs in a worker
    thread; the calls are handed to the event loop that owns the MCP client session. Reply bytes are the length of the text content the
    server really sent."""

    def __init__(self, workspace: Path, roots: "dict | None", mcp_session, loop, *, project: str = PROJECT, write: bool = True):
        super().__init__(workspace, roots, project=project, write=write)
        self._mcp, self._loop = mcp_session, loop
        self.protocol_errors: list = []

    def __enter__(self) -> "StdioSession":
        return self                                       # the server child has its own environment; nothing is patched here

    def __exit__(self, *exc) -> None:
        return None

    def call(self, tool: str, phase: str = "", **arguments) -> dict:
        name = tool if tool.startswith("gemarc_atlas_") else f"gemarc_atlas_{tool}"
        spec = next(s for s in atlas_tools.tools_of(atlas_tools.LOCAL) if s.name == name)
        if "project" in spec.fn.__code__.co_varnames[: spec.fn.__code__.co_argcount] and "project" not in arguments:
            arguments = {"project": self.project, **arguments}
        import asyncio

        started = time.perf_counter()
        result = asyncio.run_coroutine_threadsafe(self._mcp.call_tool(name, arguments), self._loop).result(timeout=600)
        seconds = time.perf_counter() - started
        text = result.content[0].text
        payload = json.loads(text)
        if len(result.content) != 1 or result.structured_content is not None or text != compact(payload) or bool(result.is_error) != (payload.get("status") in ("invalid", "error")):
            self.protocol_errors.append(name)
        self.records.append({"tool": name, "phase": phase or self.phase, "request": nbytes(arguments), "reply": len(text.encode("utf-8")),
                             "text": len(str(arguments.get("text", "")).encode("utf-8")), "seconds": round(seconds, 4), "status": payload.get("status")})
        return payload


def run_over_stdio(workspace: Path, roots: "dict | None", driver, *, project: str = PROJECT, write: bool = True, extra_env: "dict | None" = None) -> "tuple[object, list]":
    """Start the atlas server as a child process, run ``driver(StdioSession)`` against it in a worker thread, return ``(driver result, stderr lines)``."""
    import asyncio
    import sys
    import tempfile

    repo = Path(__file__).resolve().parents[2]
    browser_env = ("ProgramFiles", "ProgramFiles(x86)", "ProgramW6432", "LOCALAPPDATA", "TMP", "TEMP", "SystemRoot", "GEMARC_ATLAS_BROWSER")

    async def main():
        from mcp import ClientSession
        from mcp.client.stdio import StdioServerParameters, stdio_client

        env = {key: os.environ[key] for key in browser_env if key in os.environ}
        env.update({"GEMARC_TOOLSET": "atlas", "GEMARC_WORKSPACE_ROOT": str(workspace), "PYTHONUTF8": "1", "PYTHONPATH": str(repo / "src"),
                    "GEMARC_ALLOW_WRITE": "1" if write else "0"})
        if roots:
            env["GEMARC_ATLAS_ROOTS"] = ";".join(f"{a}={p}" for a, p in roots.items())
        env.update(extra_env or {})
        with tempfile.TemporaryDirectory(prefix="atlas-m8-cwd-") as cwd, tempfile.TemporaryFile("w+", encoding="utf-8", errors="replace") as errlog:
            params = StdioServerParameters(command=sys.executable, args=["-m", "gemarc_mcp"], env=env, cwd=cwd)
            async with stdio_client(params, errlog=errlog) as (read, write_stream):
                async with ClientSession(read, write_stream, read_timeout_seconds=600) as client:
                    await client.initialize()
                    loop = asyncio.get_running_loop()
                    stdio = StdioSession(workspace, roots, client, loop, project=project, write=write)
                    result = await loop.run_in_executor(None, driver, stdio)
            errlog.seek(0)
            return result, errlog.read().splitlines()

    return asyncio.run(main())


